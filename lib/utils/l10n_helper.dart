/// Universal translation helper for hardcoded Italian strings
// Traduce prefissi giorni IT in EN per stringhe tipo "Dom 16 Mar" -> "Sun 16 Mar"
String localizeDayPrefix(BuildContext context, String date) {
  final isEn = Localizations.localeOf(context).languageCode == 'en';
  if (!isEn) return date;
  const map = {
    'Lun ': 'Mon ', 'Mar ': 'Tue ', 'Mer ': 'Wed ', 'Gio ': 'Thu ',
    'Ven ': 'Fri ', 'Sab ': 'Sat ', 'Dom ': 'Sun ',
    'Ier ': 'Yes ', 'Oggi': 'Today', 'Domani': 'Tomorrow',
  };
  String result = date;
  for (final e in map.entries) {
    if (result.startsWith(e.key)) {
      result = e.value + result.substring(e.key.length);
      break;
    }
  }
  // Per 'Oggi' (no spazio) usa replace per intero
  if (result == 'Oggi') result = 'Today';
  if (result == 'Domani') result = 'Tomorrow';
  return result;
}

String tr(BuildContext context, String text) {
  final isEn = Localizations.localeOf(context).languageCode == 'en';
  if (!isEn) return text;
  return _map[text] ?? text;
}

/// Form initial helper: maps standard W/D/L result codes to localized
/// initials. IT: V/P/S (Vittoria/Pareggio/Sconfitta). EN: W/D/L pass-through.
/// Use this in any chip Forma rendering across the app.
String formInitial(BuildContext context, String result) {
  final isEn = Localizations.localeOf(context).languageCode == 'en';
  switch (result) {
    case 'W': return isEn ? 'W' : 'V';
    case 'D': return isEn ? 'D' : 'P';
    default:  return isEn ? 'L' : 'S';
  }
}

/// Standings/career abbreviation helper: maps Italian column headers to
/// English equivalents. In IT it passes through; in EN converts to standard
/// football abbreviations (P/W/D/L/GF/GA/GD/Pts).
String standingsAbbr(BuildContext context, String italianAbbr) {
  final isEn = Localizations.localeOf(context).languageCode == 'en';
  if (!isEn) return italianAbbr;
  switch (italianAbbr) {
    case 'G':  return 'P';    // Giocate -> Played
    case 'V':  return 'W';    // Vittorie -> Wins
    case 'P':  return 'D';    // Pareggi -> Draws
    case 'S':  return 'L';    // Sconfitte -> Losses
    case 'GF': return 'GF';   // Goal Fatti -> Goals For
    case 'GS': return 'GA';   // Goal Subiti -> Goals Against
    case 'DR': return 'GD';   // Differenza Reti -> Goal Difference
    case 'Pt': return 'Pts';  // Punti -> Points
    default:   return italianAbbr;
  }
}

